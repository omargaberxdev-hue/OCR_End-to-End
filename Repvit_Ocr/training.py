"""## 3. Model
Changes vs. your `model.py`:
- added the missing `ctc_loss` (train.py imported it but it didn't exist). It uses `ctc_input_lengths` so padding is excluded from the CTC time axis, and runs the log-softmax in fp32 (fp16 CTC is unstable under autocast).
- `wh_ace_loss` now takes the **flat targets + target_lengths** that `collate` produces, instead of a `[B, T]` matrix padded with -1. Also the tokenizer ids already include blank = 0, so the `+1` shift is gone (it would have shifted every label onto the wrong class).
- removed the unused `CTC` module.
- `forward(..., dense_only=True)` is the inference path: it never touches `SqueezeNet` and returns the 2D logit map `[B,K,H,W]`.
- `RepViTBackbone(keep_width_stages=...)` lowers the horizontal stride: 1 -> 16 px per grid column (2x the CTC time steps for the cost of the last stage only), 0 -> the original 32.
"""

import torch
from torch import nn
import torch.nn.functional as F
import timm


class RepViTBackbone(nn.Module):
    """RepViT feature extractor returning a spatial feature map [B, C, H, W].

    keep_width_stages = how many of the LAST downsampling stages keep the width (stride 2 -> (2, 1)):
      0 -> stride 32 wide x 32 high (original) | 1 -> 16 x 32 | 2 -> 8 x 32 | 3 -> 4 x 32
    Only the stride changes, so pretrained weights and old checkpoints still load."""

    def __init__(self, model_name: str = "repvit_m1_0", pretrained: bool = True, keep_width_stages: int = 1):
        super().__init__()
        self.model_name = model_name
        self.network = timm.create_model(model_name, pretrained=pretrained, num_classes=0, global_pool="")

        downs = [s.downsample for s in list(self.network.stages)[1:]]      # stage 0 has no downsample
        assert all(hasattr(d, "spatial_downsample") for d in downs), "unexpected timm RepViT layout"
        assert 0 <= keep_width_stages <= len(downs), f"keep_width_stages must be 0..{len(downs)}"
        for d in downs[len(downs) - keep_width_stages:]:
            d.spatial_downsample.c.stride = (2, 1)                          # (height, width): halve H, keep W
        self.stride_x, self.stride_y = 32 // 2 ** keep_width_stages, 32     # pixels per grid column / row

        was_training = self.network.training
        self.network.eval()
        try:
            with torch.no_grad():
                features = self._forward_features(torch.zeros(1, 3, 80, 256))
                if features.ndim != 4:
                    raise RuntimeError(f"{model_name}.forward_features returned {tuple(features.shape)}; expected [B, C, H, W].")
                self.out_channels = int(features.shape[1])
        finally:
            self.network.train(was_training)

    def _forward_features(self, images):
        features = self.network.forward_features(images)
        if isinstance(features, (tuple, list)):
            features = features[-1]
        return features

    def forward(self, images):
        return self._forward_features(images)


class SqueezeNet(nn.Module):
    """The original ExCTC column-attention module, including concentration loss."""

    def __init__(self, in_channels: int):
        super().__init__()
        self.f2map = nn.Conv2d(in_channels, 1, kernel_size=3, stride=1, padding=1)
        self.bn = nn.BatchNorm2d(1)

    def forward(self, features, temperature: float = 1.0):
        squeeze_map = F.relu(self.bn(self.f2map(features)))                # [B,1,H,W]
        concentrate_loss = 1.0 / squeeze_map.var(dim=2).mean()
        squeeze_map = F.softmax(squeeze_map / temperature, dim=2)          # softmax over height
        sequence = torch.sum(features * squeeze_map, dim=2)                # [B,C,W]
        return sequence, squeeze_map, concentrate_loss


class RepViTExCTC(nn.Module):
    def __init__(self, num_classes: int, backbone_name: str = "repvit_m1_0", pretrained: bool = True,
                 keep_width_stages: int = 1):
        super().__init__()
        self.backbone = RepViTBackbone(backbone_name, pretrained, keep_width_stages)
        channels = self.backbone.out_channels
        self.S = SqueezeNet(channels)
        self.C = nn.Linear(channels, num_classes)    # ONE classifier shared by both branches
        self.num_classes = num_classes

    def forward(self, images, temperature: float = 1.0, dense_only: bool = False):
        features = self.backbone(images)
        features = F.dropout(features, p=0.5, training=self.training)

        if dense_only:  # INFERENCE: skip SqueezeNet, classify every 2D cell with the shared classifier
            logits_2d = self.C(features.permute(0, 2, 3, 1)).permute(0, 3, 1, 2)   # [B,K,H,W]
            return {"logits_2d": logits_2d, "feature_map_2d": features}

        # CTC branch
        features_1d, squeeze_map, concentrate_loss = self.S(features, temperature)
        ctc_logits = self.C(features_1d.permute(2, 0, 1))                  # [W,B,K]

        # WH-ACE branch: same classifier on every 2D location
        B, C, H, W = features.shape
        dense = features.reshape(B, C, H * W).permute(2, 0, 1)
        dense_logits = self.C(dense)                                       # [H*W,B,K]

        return {"logits": ctc_logits, "dense_logits": dense_logits, "squeeze_map": squeeze_map,
                "concentrate_loss": concentrate_loss, "feature_map_2d": features}


def ctc_input_lengths(input_widths, padded_input_width: int, output_width: int):
    """Valid CTC steps for each unpadded image in a padded batch."""
    ratio = input_widths.float() / float(padded_input_width)
    return torch.round(ratio * output_width).long().clamp(min=1, max=output_width)


def ctc_loss(logits, targets, widths, target_lengths, padded_width: int):
    """logits [T,B,K]; targets flat [sum(L)] (ids already include blank=0); widths = unpadded pixel widths."""
    log_probs = logits.float().log_softmax(2)
    input_lengths = ctc_input_lengths(widths, padded_width, log_probs.size(0))
    return F.ctc_loss(log_probs, targets, input_lengths, target_lengths,
                      blank=0, reduction="mean", zero_infinity=True)


def wh_ace_loss(dense_logits, targets, target_lengths, normalize: bool = False):
    """
    dense_logits:   [N, B, K]  N = H*W locations, class 0 = blank
    targets:        [sum(L)]   flat class ids (blank-inclusive vocab, as produced by collate)
    target_lengths: [B]
    """
    N, B, K = dense_logits.shape
    y = dense_logits.float().softmax(dim=2).sum(0)               # [B,K] predicted mass per class
    if normalize:
        y = y / N

    h = torch.ones(B, K, device=y.device, dtype=y.dtype)         # 1 = penalize
    h[:, 0] = 0                                                  # blank is free
    batch_idx = torch.repeat_interleave(torch.arange(B, device=y.device), target_lengths)
    h[batch_idx, targets.long()] = 0                             # classes present in the label are free
    return (h * y).mean()

"""## 4. Data pipeline
Same as your `data.py`, with one addition: `width_scale`. Stretching the width x2 gives a character (~28 px at height 64) about 3.5 CTC steps at stride 16 (about 1.75 at stride 32). CTC needs spare steps for blanks between repeated letters like "ll" and for long words, so keep `max_width` large enough that `ceil(width / stride_x)` stays well above the label length.
"""

import random
from dataclasses import dataclass

import albumentations as A
import cv2
from albumentations.pytorch import ToTensorV2
from tokenizers import Regex, Tokenizer, decoders, models, normalizers, pre_tokenizers
from torch.nn.utils.rnn import pad_sequence
from torch.utils.data import Dataset
from transformers import PreTrainedTokenizerFast

IMG_KEYS = ("image", "image_path", "path", "file_name", "filename", "img")
TXT_KEYS = ("text", "transcription", "label", "gt", "word", "sentence", "text_gt")


@dataclass
class Sample:
    image: Path
    text: str
    bbox: tuple[float, float, float, float] | None = None  # x1, y1, x2, y2


def _get(d: dict, keys):
    return next((d[k] for k in keys if d.get(k) is not None), None)

def flatten(payload) -> list[dict]:
    if isinstance(payload, dict) and "images" in payload and "annotations" in payload:
        images = {str(i["id"]): i for i in payload["images"]}
        return [{**images[str(a["image_id"])], **a}
                for a in payload["annotations"] if str(a.get("image_id")) in images]
    if isinstance(payload, dict):
        payload = next((payload[k] for k in ("samples", "data", "records") if isinstance(payload.get(k), list)), [payload])
    return [d for d in payload if isinstance(d, dict)]


def load_samples(json_path: str, root: str | None = None) -> list[Sample]:
    json_path = Path(json_path)
    root = Path(root) if root else json_path.parent
    samples = []
    for d in flatten(json.loads(json_path.read_text(encoding="utf-8"))):
        img, text = _get(d, IMG_KEYS), _get(d, TXT_KEYS)
        if img is None or text is None:
            continue
        path = root / img
        if not path.exists():
            raise FileNotFoundError(f"{path}  (record: {d})")
        bbox = None
        if d.get("bbox") is not None:
            x, y, a, b = map(float, d["bbox"])
            bbox = (x, y, a, b) if d.get("bbox_format", "xywh") == "xyxy" else (x, y, x + a, y + b)
        samples.append(Sample(path, str(text), bbox))
    if not samples:
        raise ValueError(f"No usable samples in {json_path}")
    return samples


def split(samples, val_fraction: float = 0.05, seed: int = 0):
    """Split by source image so crops of one image never land in both sets."""
    images = sorted({s.image for s in samples})
    random.Random(seed).shuffle(images)
    val = set(images[: max(1, round(len(images) * val_fraction))])
    return [s for s in samples if s.image not in val], [s for s in samples if s.image in val]


def build_tokenizer(alphabet: str, lower_case: bool = False) -> PreTrainedTokenizerFast:
    """Char-level HF tokenizer. id 0 = <blank> (CTC blank / pad), 1 = <unk>. len(tok) = head size."""
    alphabet = alphabet.lower() if lower_case else alphabet
    vocab = {"<blank>": 0, "<unk>": 1}
    for ch in alphabet:
        vocab.setdefault(ch, len(vocab))
    tok = Tokenizer(models.WordLevel(vocab, unk_token="<unk>"))
    tok.normalizer = normalizers.Sequence([normalizers.NFKC()] + ([normalizers.Lowercase()] if lower_case else []))
    tok.pre_tokenizer = pre_tokenizers.Split(Regex("."), behavior="isolated")
    tok.decoder = decoders.Fuse()
    return PreTrainedTokenizerFast(tokenizer_object=tok, pad_token="<blank>", unk_token="<unk>",
                                   clean_up_tokenization_spaces=False)


def make_transform(train: bool) -> A.Compose:
    aug = [
        A.ColorJitter(brightness=0.15, contrast=0.2, saturation=0.25, hue=0.0, p=0.7),
        A.GaussianBlur(blur_limit=(3, 3), sigma_limit=(0.1, 0.55), p=0.15),
        A.GaussNoise(std_range=(0.004, 0.016), p=0.2),
    ] if train else []
    return A.Compose(aug + [A.Normalize(mean=(0.5,) * 3, std=(0.5,) * 3), ToTensorV2()])


class OCRDataset(Dataset):
    def __init__(self, samples, tokenizer, transform, height: int = 64, max_width: int = 2048,
                 width_scale: float = 2.0):
        self.samples, self.tok, self.transform = samples, tokenizer, transform
        self.height, self.max_width, self.width_scale = height, max_width, width_scale

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, i):
        s = self.samples[i]
        try:
            img = cv2.imread(str(s.image), cv2.IMREAD_COLOR)
            if img is None:
                raise IOError("cv2 could not read image")
            img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)

            if s.bbox:
                H, W = img.shape[:2]
                x1, y1 = max(0, round(s.bbox[0])), max(0, round(s.bbox[1]))
                x2, y2 = min(W, round(s.bbox[2])), min(H, round(s.bbox[3]))
                if x2 > x1 and y2 > y1:
                    img = img[y1:y2, x1:x2]

            h, w = img.shape[:2]  # fixed height, aspect-preserving (x width_scale) width, capped
            new_w = min(self.max_width, max(1, round(w * self.height / h * self.width_scale)))
            img = cv2.resize(img, (new_w, self.height))

            ids = self.tok(s.text, add_special_tokens=False)["input_ids"]
            if not ids:
                raise ValueError("empty transcription after tokenization")

            return {"image": self.transform(image=img)["image"], "target": torch.tensor(ids), "text": s.text}
        except Exception as e:
            raise RuntimeError(f"sample {i} failed: {s}") from e


def collate(batch: list[dict]) -> dict:
    # (C,H,W) -> (W,C,H) so pad_sequence pads width -> (B,W,C,H) -> (B,C,H,W)
    images = pad_sequence([b["image"].permute(2, 0, 1) for b in batch], batch_first=True).permute(0, 2, 3, 1)
    images = F.pad(images, (0, -images.shape[-1] % 32))  # width -> multiple of 32
    targets = [b["target"] for b in batch]
    return {
        "images": images,
        "widths": torch.tensor([b["image"].shape[-1] for b in batch]),
        "targets": torch.cat(targets),
        "target_lengths": torch.tensor([len(t) for t in targets]),
        "texts": [b["text"] for b in batch],
    }

"""## 5. Training code"""

import math
from dataclasses import asdict
from torch.utils.data import DataLoader
from tqdm.auto import tqdm


@dataclass
class Config:
    annotations: str = "data/annotations.json"
    alphabet: str = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 .,-!?"
    backbone: str = "repvit_m1_0"
    keep_width_stages: int = 1        # grid stride: 0 -> 32 x 32 | 1 -> 16 (wide) x 32 (high) | 2 -> 8 x 32
    epochs: int = 8
    batch_size: int = 32
    lr: float = 5e-4
    weight_decay: float = 1e-4
    min_lr: float = 1e-6
    lambda_ace: float = 1.0
    lambda_conc: float = 0.05
    grad_clip: float = 2.0
    val_fraction: float = 0.02
    seed: int = 42
    num_workers: int = 2
    checkpoint: str = "best_exctc_model.pt"


def compute_losses(model, batch: dict, cfg: Config, device) -> dict:
    """The ONE place the total loss is defined (train and val)."""
    images = batch["images"].to(device, non_blocking=True)
    targets = batch["targets"].to(device, non_blocking=True)
    widths = batch["widths"].to(device)
    tlens = batch["target_lengths"].to(device)
    out = model(images)
    ctc = ctc_loss(out["logits"], targets, widths, tlens, padded_width=images.shape[-1])
    ace = wh_ace_loss(out["dense_logits"], targets, tlens)
    conc = out["concentrate_loss"].float()
    return {"loss": ctc + cfg.lambda_ace * ace + cfg.lambda_conc * conc, "ctc": ctc, "ace": ace, "conc": conc}


def run_epoch(model, loader, cfg: Config, device, optimizer=None, scaler=None) -> dict:
    """Train if `optimizer` is given, otherwise evaluate. Returns sample-weighted mean of each loss."""
    train = optimizer is not None
    model.train(train)
    sums, seen = {}, 0
    with torch.set_grad_enabled(train):
        for batch in tqdm(loader, desc="train" if train else "val", leave=False):
            with torch.autocast(device.type, enabled=scaler is not None and scaler.is_enabled()):
                losses = compute_losses(model, batch, cfg, device)
            vals = {k: v.item() for k, v in losses.items()}
            if not math.isfinite(vals["loss"]):
                print(f"[warn] non-finite loss {vals}; skipping batch")
                continue
            if train:
                optimizer.zero_grad(set_to_none=True)
                scaler.scale(losses["loss"]).backward()
                scaler.unscale_(optimizer)
                torch.nn.utils.clip_grad_norm_(model.parameters(), cfg.grad_clip)
                scaler.step(optimizer)
                scaler.update()
            bs = len(batch["texts"])
            seen += bs
            for k, v in vals.items():
                sums[k] = sums.get(k, 0.0) + v * bs
    return {k: v / max(seen, 1) for k, v in sums.items()}


def fmt(m: dict) -> str:
    return " | ".join(f"{k}: {v:.4f}" for k, v in m.items())


def main(cfg: Config = Config()):
    torch.manual_seed(cfg.seed)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    tok = build_tokenizer(cfg.alphabet)
    train_s, val_s = split(load_samples(cfg.annotations), cfg.val_fraction, cfg.seed)
    print(f"train {len(train_s)} | val {len(val_s)} | classes {len(tok)}")

    def loader(samples, train: bool):
        return DataLoader(OCRDataset(samples, tok, make_transform(train)), batch_size=cfg.batch_size,
                          shuffle=train, num_workers=cfg.num_workers, pin_memory=device.type == "cuda",
                          collate_fn=collate)

    train_dl, val_dl = loader(train_s, True), loader(val_s, False)

    model = RepViTExCTC(num_classes=len(tok), backbone_name=cfg.backbone,
                        keep_width_stages=cfg.keep_width_stages).to(device)
    sx, sy = model.backbone.stride_x, model.backbone.stride_y
    print(f"grid cell: {sx} x {sy} px of the model input")
    optimizer = torch.optim.AdamW(model.parameters(), lr=cfg.lr, weight_decay=cfg.weight_decay)
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=cfg.epochs, eta_min=cfg.min_lr)
    scaler = torch.amp.GradScaler(device.type, enabled=device.type == "cuda")

    metric_names = {"loss": "total_loss", "ctc": "ctc_loss", "ace": "ace_loss", "conc": "conc_loss"}
    with mlflow.start_run(run_name=f"RepViT-stride{sx}x{sy}-ep{cfg.epochs}"):
        mlflow.log_params({**asdict(cfg), "stride_x": sx, "stride_y": sy, "train_size": len(train_s),
                           "val_size": len(val_s), "dataset": HF_REPO, "width_scale": 2.0, "max_width": 2048})

        best = float("inf")
        for epoch in range(1, cfg.epochs + 1):
            lr_now = optimizer.param_groups[0]["lr"]                       # the lr used in THIS epoch
            tr = run_epoch(model, train_dl, cfg, device, optimizer, scaler)
            va = run_epoch(model, val_dl, cfg, device)
            scheduler.step()
            print(f"[{epoch}/{cfg.epochs}] train {fmt(tr)}\n{' ' * len(f'[{epoch}/{cfg.epochs}]')} val   {fmt(va)}")

            for k, name in metric_names.items():
                mlflow.log_metric(f"train_{name}", tr[k], step=epoch)
                mlflow.log_metric(f"val_{name}", va[k], step=epoch)
            mlflow.log_metric("learning_rate", lr_now, step=epoch)

            if va["loss"] < best:
                best = va["loss"]
                torch.save({"epoch": epoch, "model": model.state_dict(), "optimizer": optimizer.state_dict(),
                            "val_loss": best, "alphabet": cfg.alphabet,
                            "keep_width_stages": cfg.keep_width_stages}, cfg.checkpoint)
                print(f"  saved {cfg.checkpoint}")

        # Registry: log the best CHECKPOINT (weights + alphabet + stride) and register it. We do not pickle the
        # model object: its classes live in this notebook, so the pickle could not be loaded anywhere else.
        # A registry failure must never lose the trained model, hence the try/except.
        try:
            mlflow.log_artifact(cfg.checkpoint, artifact_path="checkpoint")
            mlflow.register_model(f"runs:/{mlflow.active_run().info.run_id}/checkpoint", "RepViT-ExCTC-OCR")
            print("registered RepViT-ExCTC-OCR")
        except Exception as e:
            print(f"[warn] registry upload failed ({type(e).__name__}: {e}); checkpoint is still saved locally")
    return model

