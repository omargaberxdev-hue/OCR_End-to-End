def decode_crop(p):                                  # p: [C, Hg, Wg]
    conf, cls = p.max(0)                             # best class per cell
    seq = cls.gather(0, conf.argmax(0)[None])[0].cpu().numpy()   # best row per column
    out, prev = [], 0
    for i in seq:
        if i != prev and i > 1: out.append(id2ch[i])
        prev = i
    return "".join(out)

