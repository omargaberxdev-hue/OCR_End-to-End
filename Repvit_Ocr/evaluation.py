"""## 3. Model
Architecture only, needed to rebuild the weights or to unpickle the registered model, so the class is kept exactly as trained. Evaluation uses only the **1D CTC branch** (`model(images)["logits"]`, SqueezeNet column attention + shared classifier); the 2D head is never called.
"""

class RepViTBackbone(nn.Module):
    """RepViT feature extractor returning a spatial feature map [B, C, H, W].

    keep_width_stages = how many of the LAST downsampling stages keep the width (stride 2 -> (2, 1)):
      0 -> stride 32 wide x 32 high (original) | 1 -> 16 x 32 | 2 -> 8 x 32 | 3 -> 4 x 32
    Only the stride changes, so pretrained weights and old checkpoints still load."""

    def __init__(self, model_name: str = "repvit_m1_0", pretrained: bool = True, keep_width_stages: int = 1):
        super().__init__()
        self.model_name = model_name
        self.network = timm.create_model(model_name, pretrained=pretrained, num_classes=0, global_pool="")

        downs = [s.downsample for s in list(self.network.stages)[1:]]      # stage 0 has no downsample
        assert all(hasattr(d, "spatial_downsample") for d in downs), "unexpected timm RepViT layout"
        assert 0 <= keep_width_stages <= len(downs), f"keep_width_stages must be 0..{len(downs)}"
        for d in downs[len(downs) - keep_width_stages:]:
            d.spatial_downsample.c.stride = (2, 1)                          # (height, width): halve H, keep W
        self.stride_x, self.stride_y = 32 // 2 ** keep_width_stages, 32     # pixels per grid column / row

        was_training = self.network.training
        self.network.eval()
        try:
            with torch.no_grad():
                features = self._forward_features(torch.zeros(1, 3, 80, 256))
                if features.ndim != 4:
                    raise RuntimeError(f"{model_name}.forward_features returned {tuple(features.shape)}; expected [B, C, H, W].")
                self.out_channels = int(features.shape[1])
        finally:
            self.network.train(was_training)

    def _forward_features(self, images):
        features = self.network.forward_features(images)
        if isinstance(features, (tuple, list)):
            features = features[-1]
        return features

    def forward(self, images):
        return self._forward_features(images)


class SqueezeNet(nn.Module):
    """The original ExCTC column-attention module, including concentration loss."""

    def __init__(self, in_channels: int):
        super().__init__()
        self.f2map = nn.Conv2d(in_channels, 1, kernel_size=3, stride=1, padding=1)
        self.bn = nn.BatchNorm2d(1)

    def forward(self, features, temperature: float = 1.0):
        squeeze_map = F.relu(self.bn(self.f2map(features)))                # [B,1,H,W]
        concentrate_loss = 1.0 / squeeze_map.var(dim=2).mean()
        squeeze_map = F.softmax(squeeze_map / temperature, dim=2)          # softmax over height
        sequence = torch.sum(features * squeeze_map, dim=2)                # [B,C,W]
        return sequence, squeeze_map, concentrate_loss


class RepViTExCTC(nn.Module):
    def __init__(self, num_classes: int, backbone_name: str = "repvit_m1_0", pretrained: bool = True,
                 keep_width_stages: int = 1):
        super().__init__()
        self.backbone = RepViTBackbone(backbone_name, pretrained, keep_width_stages)
        channels = self.backbone.out_channels
        self.S = SqueezeNet(channels)
        self.C = nn.Linear(channels, num_classes)    # ONE classifier shared by both branches
        self.num_classes = num_classes

    def forward(self, images, temperature: float = 1.0, dense_only: bool = False):
        features = self.backbone(images)
        features = F.dropout(features, p=0.5, training=self.training)

        if dense_only:  # INFERENCE: skip SqueezeNet, classify every 2D cell with the shared classifier
            logits_2d = self.C(features.permute(0, 2, 3, 1)).permute(0, 3, 1, 2)   # [B,K,H,W]
            return {"logits_2d": logits_2d, "feature_map_2d": features}

        # CTC branch
        features_1d, squeeze_map, concentrate_loss = self.S(features, temperature)
        ctc_logits = self.C(features_1d.permute(2, 0, 1))                  # [W,B,K]

        # WH-ACE branch: same classifier on every 2D location
        B, C, H, W = features.shape
        dense = features.reshape(B, C, H * W).permute(2, 0, 1)
        dense_logits = self.C(dense)                                       # [H*W,B,K]

        return {"logits": ctc_logits, "dense_logits": dense_logits, "squeeze_map": squeeze_map,
                "concentrate_loss": concentrate_loss, "feature_map_2d": features}


def ctc_input_lengths(input_widths, padded_input_width: int, output_width: int):
    """Valid CTC steps for each unpadded image in a padded batch."""
    ratio = input_widths.float() / float(padded_input_width)
    return torch.round(ratio * output_width).long().clamp(min=1, max=output_width)

"""## 4. Data pipeline
Each word crop is resized to `height` px with its width stretched by `width_scale`; batches are padded in width to a multiple of 32 with 0 after normalisation, and `widths` keeps the true size so padding is excluded from the CTC time axis.
"""

IMG_KEYS = ("image", "image_path", "path", "file_name", "filename", "img")
TXT_KEYS = ("text", "transcription", "label", "gt", "word", "sentence", "text_gt")


@dataclass
class Sample:
    image: Path
    text: str
    bbox: tuple[float, float, float, float] | None = None  # x1, y1, x2, y2


def _get(d: dict, keys):
    return next((d[k] for k in keys if d.get(k) is not None), None)

def flatten(payload) -> list[dict]:
    if isinstance(payload, dict) and "images" in payload and "annotations" in payload:
        images = {str(i["id"]): i for i in payload["images"]}
        return [{**images[str(a["image_id"])], **a}
                for a in payload["annotations"] if str(a.get("image_id")) in images]
    if isinstance(payload, dict):
        payload = next((payload[k] for k in ("samples", "data", "records") if isinstance(payload.get(k), list)), [payload])
    return [d for d in payload if isinstance(d, dict)]


def load_samples(json_path: str, root: str | None = None) -> list[Sample]:
    json_path = Path(json_path)
    root = Path(root) if root else json_path.parent
    samples = []
    for d in flatten(json.loads(json_path.read_text(encoding="utf-8"))):
        img, text = _get(d, IMG_KEYS), _get(d, TXT_KEYS)
        if img is None or text is None:
            continue
        path = root / img
        if not path.exists():
            raise FileNotFoundError(f"{path}  (record: {d})")
        bbox = None
        if d.get("bbox") is not None:
            x, y, a, b = map(float, d["bbox"])
            bbox = (x, y, a, b) if d.get("bbox_format", "xywh") == "xyxy" else (x, y, x + a, y + b)
        samples.append(Sample(path, str(text), bbox))
    if not samples:
        raise ValueError(f"No usable samples in {json_path}")
    return samples


def build_tokenizer(alphabet: str, lower_case: bool = False) -> PreTrainedTokenizerFast:
    """Char-level HF tokenizer. id 0 = <blank> (CTC blank / pad), 1 = <unk>. len(tok) = head size."""
    alphabet = alphabet.lower() if lower_case else alphabet
    vocab = {"<blank>": 0, "<unk>": 1}
    for ch in alphabet:
        vocab.setdefault(ch, len(vocab))
    tok = Tokenizer(models.WordLevel(vocab, unk_token="<unk>"))
    tok.normalizer = normalizers.Sequence([normalizers.NFKC()] + ([normalizers.Lowercase()] if lower_case else []))
    tok.pre_tokenizer = pre_tokenizers.Split(Regex("."), behavior="isolated")
    tok.decoder = decoders.Fuse()
    return PreTrainedTokenizerFast(tokenizer_object=tok, pad_token="<blank>", unk_token="<unk>",
                                   clean_up_tokenization_spaces=False)


def make_transform() -> A.Compose:
    return A.Compose([A.Normalize(mean=(0.5,) * 3, std=(0.5,) * 3), ToTensorV2()])


class OCRDataset(Dataset):
    def __init__(self, samples, tokenizer, transform, height: int = 64, max_width: int = 2048,
                 width_scale: float = 2.0):
        self.samples, self.tok, self.transform = samples, tokenizer, transform
        self.height, self.max_width, self.width_scale = height, max_width, width_scale

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, i):
        s = self.samples[i]
        try:
            img = cv2.imread(str(s.image), cv2.IMREAD_COLOR)
            if img is None:
                raise IOError("cv2 could not read image")
            img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)

            if s.bbox:
                H, W = img.shape[:2]
                x1, y1 = max(0, round(s.bbox[0])), max(0, round(s.bbox[1]))
                x2, y2 = min(W, round(s.bbox[2])), min(H, round(s.bbox[3]))
                if x2 > x1 and y2 > y1:
                    img = img[y1:y2, x1:x2]

            h, w = img.shape[:2]  # fixed height, aspect-preserving (x width_scale) width, capped
            new_w = min(self.max_width, max(1, round(w * self.height / h * self.width_scale)))
            img = cv2.resize(img, (new_w, self.height))

            ids = self.tok(s.text, add_special_tokens=False)["input_ids"]
            if not ids:
                raise ValueError("empty transcription after tokenization")

            return {"image": self.transform(image=img)["image"], "target": torch.tensor(ids), "text": s.text}
        except Exception as e:
            raise RuntimeError(f"sample {i} failed: {s}") from e


def collate(batch: list[dict]) -> dict:
    # (C,H,W) -> (W,C,H) so pad_sequence pads width -> (B,W,C,H) -> (B,C,H,W)
    images = pad_sequence([b["image"].permute(2, 0, 1) for b in batch], batch_first=True).permute(0, 2, 3, 1)
    images = F.pad(images, (0, -images.shape[-1] % 32))  # width -> multiple of 32
    targets = [b["target"] for b in batch]
    return {
        "images": images,
        "widths": torch.tensor([b["image"].shape[-1] for b in batch]),
        "targets": torch.cat(targets),
        "target_lengths": torch.tensor([len(t) for t in targets]),
        "texts": [b["text"] for b in batch],
    }

"""## 5. Decoding and metrics
- `ctc_collapse`: greedy CTC (drop repeats, blank 0 and `<unk>` 1). With `gap` set it inserts a space where two emitted characters are more than `gap` columns apart, because the training data (single words) never contains a space target.
- Metrics: `cer` = total edit distance / total reference characters; `acc` = exact match; `acc_ci` = case-insensitive alphanumeric match (usual scene-text protocol); `cer_nospace` ignores spaces.
"""

def id2ch_from(tok):
    return {i: c for c, i in tok.get_vocab().items()}


def ctc_collapse(ids, id2ch, gap=None):
    """Greedy CTC collapse. `gap` (columns): insert " " between emitted characters further apart than that."""
    out, prev, last_x = [], 0, None
    for x, i in enumerate(ids):
        i = int(i)
        if i != prev and i > 1:
            if gap is not None and last_x is not None and x - last_x > gap:
                out.append(" ")
            out.append(id2ch[i])
            last_x = x
        prev = i
    return "".join(out)


def text_metrics(gts, preds):
    nos = lambda s: s.replace(" ", "")
    e = sum(editdistance.eval(p, g) for p, g in zip(preds, gts))
    n = sum(len(g) for g in gts)
    e2 = sum(editdistance.eval(nos(p), nos(g)) for p, g in zip(preds, gts))
    n2 = sum(len(nos(g)) for g in gts)
    return {"cer": e / max(n, 1), "cer_nospace": e2 / max(n2, 1)}

"""**5b. Word crops.** Batched greedy decoding of the 1D CTC logits; the time axis is cut to each image's true width, so padding never contributes."""

def _norm(s):
    return "".join(ch for ch in s.lower() if ch.isalnum())


def crop_metrics(gts, preds):
    return {"cer": sum(editdistance.eval(p, g) for p, g in zip(preds, gts)) / max(sum(len(g) for g in gts), 1),
            "acc": float(np.mean([p == g for p, g in zip(preds, gts)])),
            "acc_ci": float(np.mean([_norm(p) == _norm(g) for p, g in zip(preds, gts)]))}


@torch.no_grad()
def predict_batch(model, images, widths, id2ch):
    logits = model(images)["logits"]                                       # [T,B,K]  1D CTC branch
    lens = ctc_input_lengths(widths, images.shape[-1], logits.shape[0]).tolist()
    ids = logits.argmax(2).T.cpu().numpy()                                 # [B,T]
    return [ctc_collapse(ids[b, :n], id2ch) for b, n in enumerate(lens)]


@torch.no_grad()
def evaluate_crops(model, samples, tok, cfg, device, batch_size=64):
    """Word-crop metrics. `rows` = [(gt, pred)]."""
    id2ch = id2ch_from(tok)
    ds = OCRDataset(samples, tok, make_transform(), cfg.height, cfg.max_width, cfg.width_scale)
    dl = DataLoader(ds, batch_size=batch_size, shuffle=False, num_workers=cfg.num_workers, collate_fn=collate)
    model.eval()
    gts, preds = [], []
    for batch in tqdm(dl, desc="eval", leave=False):
        preds += predict_batch(model, batch["images"].to(device), batch["widths"], id2ch)
        gts += batch["texts"]
    return {"n": len(gts), "metrics": crop_metrics(gts, preds), "rows": list(zip(gts, preds))}


def worst_errors(ev, k=15):
    """Print the k predictions with the largest edit distance."""
    rows = sorted(((editdistance.eval(p, g), g, p) for g, p in ev["rows"]), reverse=True)[:k]
    for d, g, p in rows:
        print(f"{d:>3}  GT={g!r:<26} PRED={p!r}")

"""**5c. Multi-line tools.** The 1D branch collapses the height, so it reads **one line at a time**.
- `build_synthetic_pages`: stitches held-out word crops into pages with known ground truth. Lines are 64 px tall with random gaps and top offset; each record stores the page text per line and the box of every line.
- `predict_line`: one line crop → resized to 64 px high, width x2, padded to a multiple of 32 with mid-grey → 1D logits (true width only) → greedy CTC with spaces from column gaps.
- `evaluate_lines`: crops every line with its box, reads it, and scores the page text (lines joined with newlines) plus the fraction of exactly correct lines.
"""

PAD_VALUE = 127      # ~ the pixel value that normalises to 0 = what collate() pads training batches with


@torch.no_grad()
def predict_line(model, img_rgb, id2ch, tf, device, height=64, width_scale=2.0, space_gap=6):
    H, W = img_rgb.shape[:2]
    im = cv2.resize(img_rgb, (max(1, round(W * height / H * width_scale)), height))
    w = im.shape[1]
    im = cv2.copyMakeBorder(im, 0, 0, 0, -w % 32, cv2.BORDER_CONSTANT, value=(PAD_VALUE,) * 3)
    model.eval()
    x = tf(image=im)["image"].unsqueeze(0).to(device)
    logits = model(x)["logits"]                                            # [T,1,K]
    n = ctc_input_lengths(torch.tensor([w]), x.shape[-1], logits.shape[0]).item()
    return ctc_collapse(logits[:n, 0].argmax(-1).cpu().numpy(), id2ch, gap=space_gap)


def build_synthetic_pages(samples, n_pages, out_dir, seed=0, page_h=512, line_h=64, word_gap=40, max_line_w=900,
                          lines_per_page=(3, 5), words_per_line=(2, 4), gap_range=(32, 40)):
    rng = random.Random(seed)
    out = Path(out_dir)
    (out / "images").mkdir(parents=True, exist_ok=True)

    def word_img(s):
        im = cv2.cvtColor(cv2.imread(str(s.image)), cv2.COLOR_BGR2RGB)
        h, w = im.shape[:2]
        return cv2.resize(im, (max(1, round(w * line_h / h)), line_h))

    records = []
    for k in range(n_pages):
        top = rng.randint(0, 31)                                   # random phase against the 32 px grid
        n_lines = rng.randint(*lines_per_page)
        while top + n_lines * line_h + (n_lines - 1) * gap_range[1] > page_h:     # must fit the page height
            n_lines -= 1
        rows = []                                                  # per line: (tiles, width)
        for _ in range(n_lines):
            tiles, x = [], 0
            for _ in range(rng.randint(*words_per_line)):
                s = rng.choice(samples)
                im = word_img(s)
                if tiles and x + word_gap + im.shape[1] > max_line_w:
                    break
                x += word_gap if tiles else 0
                tiles.append((x, im, s.text))
                x += im.shape[1]
            rows.append((tiles, x))
        ys, y = [], top
        for _ in rows:
            ys.append(y)
            y += line_h + rng.randint(*gap_range)
        canvas = np.full((page_h, max(w for _, w in rows) + 32, 3), 255, np.uint8)
        lines, boxes = [], []
        for (tiles, w), y0 in zip(rows, ys):
            for x0, im, _ in tiles:
                canvas[y0:y0 + line_h, 16 + x0:16 + x0 + im.shape[1]] = im
            lines.append(" ".join(t for _, _, t in tiles))
            boxes.append([16, y0, 16 + w, y0 + line_h])
        name = f"images/{k:05d}.png"
        cv2.imwrite(str(out / name), cv2.cvtColor(canvas, cv2.COLOR_RGB2BGR))
        records.append({"image": name, "lines": lines, "boxes": boxes})
    (out / "annotations.json").write_text(json.dumps(records), encoding="utf-8")
    return records


def _read_rgb(path):
    img = cv2.imread(str(path))
    assert img is not None, f"cannot read {path}"
    return cv2.cvtColor(img, cv2.COLOR_BGR2RGB)


def evaluate_lines(model, records, root, id2ch, tf, device, cfg):
    """Read every line of every page from its box. Returns (metrics, predicted_pages)."""
    gts, preds, hits, n_lines = [], [], 0, 0
    for r in tqdm([r for r in records if r.get("boxes")], desc="pages", leave=False):
        img = _read_rgb(Path(root) / r["image"])
        pred = [predict_line(model, img[y1:y2, x1:x2], id2ch, tf, device, cfg.height, cfg.width_scale, cfg.space_gap)
                for x1, y1, x2, y2 in r["boxes"]]
        gts.append("\n".join(r["lines"])); preds.append("\n".join(pred))
        hits += sum(p == g for p, g in zip(pred, r["lines"])); n_lines += len(r["lines"])
    m = text_metrics(gts, preds)
    m["line_acc"] = hits / max(n_lines, 1)
    m["n"] = len(gts)
    return m, preds

"""## 6. Load the model from MLflow
`cfg.model_source = "registry"` loads the pickled model `cfg.registry_uri` (the model registered earlier); if that fails (e.g. a class mismatch) it falls back to `"checkpoint"`, which downloads `checkpoint/<file>` from run `cfg.run_id` and rebuilds the model from the weights. Both need the model classes from section 3.
"""

def load_model(cfg: Config, device):
    mlflow.set_tracking_uri(f"https://dagshub.com/{cfg.repo_owner}/{cfg.repo_name}.mlflow")
    source = cfg.model_source
    if source == "registry":
        try:
            model = mlflow.pytorch.load_model(cfg.registry_uri, map_location=device)
            return model.to(device).eval(), build_tokenizer(cfg.alphabet), f"registry {cfg.registry_uri}"
        except Exception as e:
            print(f"[warn] registry load failed ({type(e).__name__}: {e}); falling back to the run checkpoint")
    path = mlflow.artifacts.download_artifacts(run_id=cfg.run_id, artifact_path=f"checkpoint/{Path(cfg.checkpoint).name}")
    ckpt = torch.load(path, map_location=device, weights_only=False)
    tok = build_tokenizer(ckpt["alphabet"])
    model = RepViTExCTC(num_classes=len(tok), backbone_name=cfg.backbone, pretrained=False,
                        keep_width_stages=ckpt.get("keep_width_stages", cfg.keep_width_stages)).to(device)
    model.load_state_dict(ckpt["model"])
    return model.eval(), tok, f"checkpoint of run {cfg.run_id} (epoch {ckpt.get('epoch', '?')})"


model, tok, MODEL_INFO = load_model(cfg, device)
assert len(tok) == model.num_classes, f"tokenizer has {len(tok)} classes, model head has {model.num_classes}"
id2ch = id2ch_from(tok)
tf = make_transform()
print(f"{MODEL_INFO} | classes {len(tok)} | grid cell {model.backbone.stride_x} x {model.backbone.stride_y} px")

